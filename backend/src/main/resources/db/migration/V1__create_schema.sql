-- Quantity invariants are enforced by CHECK constraints as a last line of defence: a transaction that would
-- violate them fails and rolls back instead of committing an inconsistent state.

CREATE TABLE product (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku                 VARCHAR(64)              NOT NULL,
    name                VARCHAR(200)             NOT NULL,
    unit_price          NUMERIC(19, 2)           NOT NULL,
    low_stock_threshold INT                      NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_product_sku UNIQUE (sku),
    CONSTRAINT ck_product_unit_price CHECK (unit_price > 0),
    CONSTRAINT ck_product_low_stock_threshold CHECK (low_stock_threshold >= 0)
);

-- available = on_hand - reserved is derived, never stored.
CREATE TABLE inventory (
    product_id BIGINT PRIMARY KEY,
    on_hand    INT NOT NULL,
    reserved   INT NOT NULL,
    CONSTRAINT fk_inventory_product FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT ck_inventory_quantities CHECK (on_hand >= 0 AND reserved >= 0 AND reserved <= on_hand)
);

CREATE TABLE stock_receipt (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT                   NOT NULL,
    quantity    INT                      NOT NULL,
    source      VARCHAR(20)              NOT NULL,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_stock_receipt_product FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT ck_stock_receipt_quantity CHECK (quantity > 0),
    CONSTRAINT ck_stock_receipt_source CHECK (source IN ('PURCHASE', 'RETURN'))
);
CREATE INDEX ix_stock_receipt_product ON stock_receipt (product_id, received_at);

-- stock_released_at is set exactly when stock goes back to availability (CANCELLED or EXPIRED). An ACTIVE row whose
-- expires_at has passed is logically expired but still holds its stock until the sweeper marks it EXPIRED.
CREATE TABLE reservation (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key     VARCHAR(100),
    request_fingerprint VARCHAR(64),
    status              VARCHAR(20)              NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    confirmed_at        TIMESTAMP WITH TIME ZONE,
    stock_released_at   TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_reservation_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT ck_reservation_status CHECK (status IN ('ACTIVE', 'CONFIRMED', 'CANCELLED', 'EXPIRED')),
    CONSTRAINT ck_reservation_confirmed CHECK ((status = 'CONFIRMED') = (confirmed_at IS NOT NULL)),
    CONSTRAINT ck_reservation_released CHECK ((status IN ('CANCELLED', 'EXPIRED')) = (stock_released_at IS NOT NULL))
);
CREATE INDEX ix_reservation_status_expires_at ON reservation (status, expires_at);

CREATE TABLE reservation_item (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT         NOT NULL,
    product_id     BIGINT         NOT NULL,
    quantity       INT            NOT NULL,
    unit_price     NUMERIC(19, 2) NOT NULL,
    CONSTRAINT fk_reservation_item_reservation FOREIGN KEY (reservation_id) REFERENCES reservation (id),
    CONSTRAINT fk_reservation_item_product FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT uk_reservation_item_product UNIQUE (reservation_id, product_id),
    CONSTRAINT ck_reservation_item_quantity CHECK (quantity > 0)
);

-- One order per reservation, created when payment is confirmed. net total = gross_total - credited_total.
CREATE TABLE customer_order (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id    BIGINT                   NOT NULL,
    payment_reference VARCHAR(100)             NOT NULL,
    status            VARCHAR(20)              NOT NULL,
    gross_total       NUMERIC(19, 2)           NOT NULL,
    credited_total    NUMERIC(19, 2)           NOT NULL,
    confirmed_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    delivered_at      TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_customer_order_reservation FOREIGN KEY (reservation_id) REFERENCES reservation (id),
    CONSTRAINT uk_customer_order_reservation UNIQUE (reservation_id),
    CONSTRAINT uk_customer_order_payment_reference UNIQUE (payment_reference),
    CONSTRAINT ck_customer_order_status CHECK (status IN ('CONFIRMED', 'IN_FULFILMENT', 'DELIVERED')),
    CONSTRAINT ck_customer_order_delivered CHECK ((status = 'DELIVERED') = (delivered_at IS NOT NULL)),
    CONSTRAINT ck_customer_order_credit CHECK (credited_total >= 0 AND credited_total <= gross_total)
);
CREATE INDEX ix_customer_order_delivered_at ON customer_order (delivered_at);

-- Per-item fulfilment counters; see OrderItem for what each one means.
CREATE TABLE order_item (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id           BIGINT         NOT NULL,
    product_id         BIGINT         NOT NULL,
    unit_price         NUMERIC(19, 2) NOT NULL,
    quantity           INT            NOT NULL,
    packed_quantity    INT            NOT NULL,
    shipped_quantity   INT            NOT NULL,
    delivered_quantity INT            NOT NULL,
    returned_quantity  INT            NOT NULL,
    CONSTRAINT fk_order_item_order FOREIGN KEY (order_id) REFERENCES customer_order (id),
    CONSTRAINT fk_order_item_product FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT uk_order_item_product UNIQUE (order_id, product_id),
    CONSTRAINT ck_order_item_quantity CHECK (quantity > 0),
    CONSTRAINT ck_order_item_progress CHECK (
        returned_quantity >= 0
        AND returned_quantity <= delivered_quantity
        AND delivered_quantity <= shipped_quantity
        AND shipped_quantity <= packed_quantity
        AND packed_quantity <= quantity)
);

CREATE TABLE shipment (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            BIGINT                   NOT NULL,
    idempotency_key     VARCHAR(100),
    request_fingerprint VARCHAR(64),
    status              VARCHAR(20)              NOT NULL,
    packed_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    shipped_at          TIMESTAMP WITH TIME ZONE,
    delivered_at        TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_shipment_order FOREIGN KEY (order_id) REFERENCES customer_order (id),
    CONSTRAINT uk_shipment_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT ck_shipment_status CHECK (status IN ('PACKED', 'SHIPPED', 'DELIVERED')),
    CONSTRAINT ck_shipment_shipped CHECK ((status IN ('SHIPPED', 'DELIVERED')) = (shipped_at IS NOT NULL)),
    CONSTRAINT ck_shipment_delivered CHECK ((status = 'DELIVERED') = (delivered_at IS NOT NULL))
);
CREATE INDEX ix_shipment_order ON shipment (order_id);

CREATE TABLE shipment_item (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id   BIGINT NOT NULL,
    order_item_id BIGINT NOT NULL,
    quantity      INT    NOT NULL,
    CONSTRAINT fk_shipment_item_shipment FOREIGN KEY (shipment_id) REFERENCES shipment (id),
    CONSTRAINT fk_shipment_item_order_item FOREIGN KEY (order_item_id) REFERENCES order_item (id),
    CONSTRAINT uk_shipment_item_order_item UNIQUE (shipment_id, order_item_id),
    CONSTRAINT ck_shipment_item_quantity CHECK (quantity > 0)
);

CREATE TABLE order_return (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            BIGINT                   NOT NULL,
    idempotency_key     VARCHAR(100),
    request_fingerprint VARCHAR(64),
    returned_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_order_return_order FOREIGN KEY (order_id) REFERENCES customer_order (id),
    CONSTRAINT uk_order_return_idempotency_key UNIQUE (idempotency_key)
);
CREATE INDEX ix_order_return_order ON order_return (order_id);

CREATE TABLE return_item (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_id      BIGINT         NOT NULL,
    order_item_id  BIGINT         NOT NULL,
    quantity       INT            NOT NULL,
    reason         VARCHAR(30)    NOT NULL,
    item_condition VARCHAR(20)    NOT NULL,
    disposition    VARCHAR(20)    NOT NULL,
    refund_amount  NUMERIC(19, 2) NOT NULL,
    CONSTRAINT fk_return_item_return FOREIGN KEY (return_id) REFERENCES order_return (id),
    CONSTRAINT fk_return_item_order_item FOREIGN KEY (order_item_id) REFERENCES order_item (id),
    CONSTRAINT ck_return_item_quantity CHECK (quantity > 0),
    CONSTRAINT ck_return_item_reason
        CHECK (reason IN ('NO_LONGER_NEEDED', 'WRONG_ITEM_SENT', 'DEFECTIVE', 'DAMAGED_IN_TRANSIT')),
    CONSTRAINT ck_return_item_condition CHECK (item_condition IN ('UNOPENED', 'OPENED', 'DAMAGED')),
    CONSTRAINT ck_return_item_disposition CHECK (disposition IN ('RESTOCK', 'DISCARD')),
    CONSTRAINT ck_return_item_refund CHECK (refund_amount >= 0)
);

-- Simulated credit note: one per return, for the sum of its refund amounts.
CREATE TABLE credit_note (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_id BIGINT                   NOT NULL,
    amount    NUMERIC(19, 2)           NOT NULL,
    issued_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_credit_note_return FOREIGN KEY (return_id) REFERENCES order_return (id),
    CONSTRAINT uk_credit_note_return UNIQUE (return_id),
    CONSTRAINT ck_credit_note_amount CHECK (amount > 0)
);
